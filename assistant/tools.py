"""The ONLY things the AI agent is allowed to do.

Each Tool has:
  - a name and typed, validated parameters
  - a handler (ordinary Python written by you, not generated by the AI)
  - an optional `confirm_if` function. If it returns text, Jarvis reads that text
    aloud and runs the tool only after you say yes. The text is built here,
    from the validated arguments, so the AI cannot word it to mislead you.

The AI proposes {"tool": ..., "args": {...}}. Nothing runs until the
registry has checked the tool name, every argument, and the confirmation rule.
"""
from __future__ import annotations

import logging
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

logger = logging.getLogger(__name__)

CANCELLED = "Cancelled. I did not do it."


@dataclass(frozen=True)
class Param:
    name: str
    type: str = "str"            # "str" | "int" | "bool"
    description: str = ""
    required: bool = True
    choices: tuple[str, ...] = ()
    min: int | None = None
    max: int | None = None
    max_len: int = 2000


@dataclass(frozen=True)
class Tool:
    name: str
    description: str
    handler: Callable[[dict], str]
    params: tuple[Param, ...] = ()
    # Returns a yes/no question when this exact call needs your approval.
    confirm_if: Callable[[dict], str | None] | None = None
    # True when the result is information the AI needs to see (search results,
    # file contents...). False when the result can simply be read back to you.
    returns_data: bool = False
    # Optional switch, e.g. file deletion disabled in config.
    available: Callable[[], bool] | None = None
    unavailable_message: str = "That action is turned off in your settings."


class ToolError(ValueError):
    pass


def _coerce(param: Param, value: Any) -> Any:
    if param.type == "int":
        if isinstance(value, bool) or not isinstance(value, (int, float, str)):
            raise ToolError(f"'{param.name}' must be a number.")
        try:
            number = int(float(value))
        except ValueError as error:
            raise ToolError(f"'{param.name}' must be a number.") from error
        if param.min is not None and number < param.min:
            raise ToolError(f"'{param.name}' must be at least {param.min}.")
        if param.max is not None and number > param.max:
            raise ToolError(f"'{param.name}' must be at most {param.max}.")
        return number
    if param.type == "bool":
        if isinstance(value, bool):
            return value
        if isinstance(value, str) and value.lower() in {"true", "false", "yes", "no"}:
            return value.lower() in {"true", "yes"}
        raise ToolError(f"'{param.name}' must be true or false.")
    # str
    if not isinstance(value, (str, int, float)) or isinstance(value, bool):
        raise ToolError(f"'{param.name}' must be text.")
    text = str(value)
    if "\x00" in text:
        raise ToolError(f"'{param.name}' contains an invalid character.")
    if len(text) > param.max_len:
        raise ToolError(f"'{param.name}' is too long.")
    if param.choices:
        text = text.strip().lower()
        if text not in param.choices:
            raise ToolError(f"'{param.name}' must be one of: {', '.join(param.choices)}.")
    return text


class ToolRegistry:
    def __init__(self):
        self._tools: dict[str, Tool] = {}

    def register(self, tool: Tool) -> None:
        if tool.name in self._tools:
            raise ValueError(f"Duplicate tool: {tool.name}")
        self._tools[tool.name] = tool

    def get(self, name: str) -> Tool | None:
        return self._tools.get(name)

    def names(self) -> list[str]:
        return list(self._tools)

    def validate(self, tool: Tool, args: Any) -> dict:
        if args is None:
            args = {}
        if not isinstance(args, dict):
            raise ToolError("Arguments must be an object.")
        known = {p.name: p for p in tool.params}
        unknown = set(args) - set(known)
        if unknown:
            raise ToolError(f"Unknown argument: {', '.join(sorted(unknown))}.")
        clean: dict[str, Any] = {}
        for param in tool.params:
            if param.name in args and args[param.name] is not None:
                clean[param.name] = _coerce(param, args[param.name])
            elif param.required:
                raise ToolError(f"Missing '{param.name}'.")
        return clean

    def describe(self) -> str:
        """Compact tool list for the AI's instructions."""
        lines = []
        for tool in self._tools.values():
            if tool.available is not None and not tool.available():
                continue
            parts = []
            for p in tool.params:
                kind = p.type if not p.choices else "|".join(p.choices)
                optional = "" if p.required else "?"
                parts.append(f"{p.name}{optional}: {kind}")
            lines.append(f"- {tool.name}({', '.join(parts)}): {tool.description}")
        return "\n".join(lines)

    def execute(self, name: str, args: Any, confirm: Callable[[str], bool] | None) -> tuple[str, Tool | None]:
        """Run one tool call. Returns (result_text, tool). Never raises."""
        tool = self._tools.get(name) if isinstance(name, str) else None
        if tool is None:
            logger.warning("Agent asked for an unknown tool")
            return f"I don't have a tool called '{name}'.", None
        if tool.available is not None and not tool.available():
            return tool.unavailable_message, tool
        try:
            clean = self.validate(tool, args)
        except ToolError as error:
            return f"I can't do that: {error}", tool

        try:
            question = tool.confirm_if(clean) if tool.confirm_if else None
        except Exception as error:
            logger.error("Confirmation check failed for %s (%s)", name, type(error).__name__)
            return "I couldn't check whether that is safe, so I didn't do it.", tool
        if question:
            if confirm is None:
                return "That needs your approval, and I can't ask right now.", tool
            logger.info("Asking for confirmation: %s", name)
            if not confirm(question):
                logger.info("Confirmation declined: %s", name)
                return CANCELLED, tool

        logger.info("Tool run: %s", name)  # names only, never the arguments
        try:
            return str(tool.handler(clean)), tool
        except Exception as error:
            logger.error("Tool failed: %s (%s)", name, type(error).__name__)
            return f"Something went wrong while running {name}.", tool
