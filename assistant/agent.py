"""Stage 9: the "do what I ask" agent.

How it stays safe while being flexible
--------------------------------------
1. The AI never gets a shell. It replies with JSON naming approved TOOLS.
2. assistant/tools.py validates the tool name and every argument.
3. Risky calls (closing windows, moving/overwriting files, deleting, power) make
   Jarvis ask you "yes or no?" out loud first. The question is generated by the
   program from the validated arguments, not by the AI.
4. What Jarvis tells you afterwards is the real result the tool returned, so it
   cannot claim something happened that did not.
5. Tool results (file contents, clipboard...) are handed back to the AI marked as
   untrusted data, and even if text in a file tried to give orders, it can still only
   reach the same approved, validated, confirm-gated tools.
"""
