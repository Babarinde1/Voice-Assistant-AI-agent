def _open_website(args: dict) -> str:
    target = args["site"].strip()
    if re.match(r"^https?://", target, re.I):
        parsed = urlparse(target)
        if not parsed.hostname or not _HOST.match(parsed.hostname) or len(target) > 500:
            return "I don't recognise that web address."
        url, label = target, parsed.hostname
    else:
        domain = resolve_site(target)
        if not domain:
            return "I don't recognise that website."
        url, label = "https://" + domain, domain
    return f"Opening {label}." if webbrowser.open(url) else "I could not open your web browser."


